logger = logging.getLogger(__name__)

EXPECTED_ITEMS = 5
_WORD = re.compile(r"[a-z0-9]+")
_GENERIC_WORDS = frozenset(
    {"and", "the", "for", "with", "our", "your", "service", "services", "solution", "solutions"}
)

# Explains to API consumers how much trust each part of the response deserves.
SOURCE_CLASSIFICATION = {
    "brand": "Summarised by the LLM from content extracted from the website.",
    "analysis.competitor_analysis.verified_information": (
        "Facts stated on the analysed website (extracted)."
    ),
    "analysis.competitor_analysis.competitors": (
        "Each competitor carries source_classification: 'verified' (backed by external "
        "research evidence) or 'ai_suggested' (unverified AI-generated suggestion)."
    ),
    "analysis.competitor_analysis.strengths|opportunities|inferred_insights": (
        "Inferred insights generated by the LLM; not verified facts."
    ),
    "analysis.target_search_queries": (
        "AI-generated keyword suggestions. No search-volume, keyword-difficulty or ranking "
        "data was used."
    ),
    "analysis.seo_improvements": (
        "AI-generated recommendations based on website content; not backed by SEO tool data. "
        "current_title and current_meta_description are extracted from the website."
    ),
    "analysis.top_services": (
        "Each service carries source_classification: 'extracted' (stated on the website), "
        "'inferred' (implied by the content) or 'suggested_opportunity' (not offered today)."
    ),
    "analysis.target_audience": "Inferred by the LLM from the website's offer and positioning.",
    "metadata.extraction_metadata": "Collected directly from the website (extracted).",
}


def is_supported_by_content(phrase: str, corpus: str) -> bool:
    """Check whether ``phrase``, or most of its significant words, occurs in ``corpus``.

    ``corpus`` must be lower-cased. This is a deliberately simple lexical check
    used to catch services labelled "extracted" that the website never mentions.
    """
    phrase = " ".join(phrase.lower().split())
    if not phrase:
        return False
    if phrase in corpus:
        return True
    words = [w for w in _WORD.findall(phrase) if len(w) > 2 and w not in _GENERIC_WORDS]
    if not words:
        return False
    return sum(word in corpus for word in words) / len(words) >= 0.6


def verify_service_sources(
    services: list[ServiceItem], corpus: str
) -> tuple[list[ServiceItem], list[str]]:
    """Downgrade "extracted" services that cannot be matched to website content."""
    verified: list[ServiceItem] = []
    warnings: list[str] = []
    for service in services:
        if service.source_classification is ServiceSource.EXTRACTED and not (
            is_supported_by_content(service.name, corpus)
            or is_supported_by_content(service.evidence, corpus)
        ):
            service = service.model_copy(update={"source_classification": ServiceSource.INFERRED})
            warnings.append(
                f"Service '{service.name}' was reclassified from 'extracted' to 'inferred' "
                "because it could not be matched to the website content."
            )
        verified.append(service)
    return verified, warnings


class AnalysisService:
    """Runs the full pipeline: validate, extract, research, generate, assemble."""

    def __init__(
        self,
        *,
        settings: Settings,
        extractor: WebsiteExtractor,
        llm_service: LLMService,
        competitor_service: CompetitorService,
        cache: TTLCache[LinkAnalysisResponse] | None = None,
    ) -> None:
        self._settings = settings
        self._extractor = extractor
        self._llm = llm_service
        self._competitors = competitor_service
        self._cache = cache or TTLCache(settings.cache_ttl_seconds, settings.cache_max_entries)

    async def analyze(self, url: str) -> LinkAnalysisResponse:
        """Analyse the website at ``url``.

        Raises:
            InvalidURLError, ForbiddenDestinationError, RobotsDisallowedError,
            WebsiteFetchError, WebsiteTimeoutError, LLMConfigurationError, LLMError.
        """
        started = time.perf_counter()
        target = validate_public_url(url, self._settings.allowed_ports)
        # Fail fast: do not crawl a website if the analysis cannot be generated.
        self._llm.ensure_configured()

        cache_key = f"{self._llm.provider_name}:{self._llm.model_name}:{target.url}"
        cached = self._cache.get(cache_key)
        if cached is not None:
            logger.info("analysis served from cache", extra={"host": target.host})
            metadata = cached.metadata.model_copy(
                update={"cached": True, "processing_time_ms": _elapsed_ms(started)}
            )
            return cached.model_copy(update={"website": url.strip(), "metadata": metadata})

        site = await self._extractor.extract(target)
        research = await self._competitors.gather_research(site)
        user_prompt = build_user_prompt(site, self._competitors.build_prompt_section(research))
        result = await self._llm.generate_analysis(SYSTEM_PROMPT, user_prompt)

        response = self._build_response(url.strip(), site, result, research, started)
        self._cache.set(cache_key, response)
        logger.info(
            "analysis completed",
            extra={
                "host": target.host,
                "provider": result.provider,
                "model": result.model,
                "warnings": len(response.warnings),
                "duration_ms": response.metadata.processing_time_ms,
            },
        )
        return response

    def _build_response(
        self,
        website: str,
        site: ExtractedWebsite,
        result: LLMResult,
        research: CompetitorResearchContext,
        started: float,
    ) -> LinkAnalysisResponse:
        """Combine extracted facts and the LLM draft into the final response."""
        draft = result.draft
        warnings = list(site.warnings)

        competitor_analysis, competitor_warnings = self._competitors.finalize(
            draft.competitor_analysis, draft.brand, research
        )
        services, service_warnings = verify_service_sources(draft.top_services, site.corpus)
        warnings += competitor_warnings + service_warnings

        if len(draft.target_search_queries) < EXPECTED_ITEMS:
            warnings.append(
                f"Only {len(draft.target_search_queries)} of {EXPECTED_ITEMS} search queries "
                "could be generated from the available content."
            )
        if len(services) < EXPECTED_ITEMS:
            warnings.append(
                f"Only {len(services)} of {EXPECTED_ITEMS} services could be identified from "
                "the available content."
            )
        if any(s.source_classification is ServiceSource.SUGGESTED_OPPORTUNITY for s in services):
            warnings.append(
                "Some top_services entries are suggested opportunities, not services the "
                "website currently offers; see each item's source_classification."
            )
        if result.used_fallback:
            warnings.append(
                f"The primary AI provider failed; this analysis was generated by the fallback "
                f"provider '{result.provider}'."
            )

        analysis = Analysis(
            competitor_analysis=competitor_analysis,
            target_search_queries=[
                SearchQuery(**query.model_dump()) for query in draft.target_search_queries
            ],
            seo_improvements=SEOImprovements(
                **draft.seo_improvements.model_dump(),
                current_title=site.title,
                current_meta_description=site.meta_description,
            ),
            top_services=services,
            target_audience=draft.target_audience,
        )
        metadata = AnalysisMetadata(
            analysis_timestamp=datetime.now(UTC),
            llm_provider=result.provider,
            llm_model=result.model,
            token_usage=TokenUsage(
                input_tokens=result.input_tokens, output_tokens=result.output_tokens
            ),
            processing_time_ms=_elapsed_ms(started),
            extraction_metadata=ExtractionMetadata(
                final_url=site.final_url,
                pages_analyzed=[page.url for page in site.pages],
                content_characters=site.content_chars,
                content_truncated=site.content_truncated,
                social_links=[link.url for link in site.social_links],
                contact_details=ContactDetails(
                    emails=site.emails, phones=site.phones, addresses=site.addresses
                ),
            ),
            source_classification=SOURCE_CLASSIFICATION,
        )
        return LinkAnalysisResponse(
            website=website,
            brand=draft.brand,
            analysis=analysis,
            warnings=unique(warnings),
            missing_information=unique(draft.missing_information),
            metadata=metadata,
        )


def _elapsed_ms(started: float) -> int:
    return round((time.perf_counter() - started) * 1000)
